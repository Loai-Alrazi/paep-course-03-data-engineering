import numpy as np
import pandas as pd


# ==========================================================
# إعداد مسارات الملفات
# ==========================================================

# ملف البيانات الخام الذي سنقرأ منه
INPUT_FILE = (
    "data/raw/"
    "students_performance.csv"
)

# الملف النهائي بعد التنظيف والتحويل والتحقق
OUTPUT_FILE = (
    "data/processed/"
    "student_analytics.csv"
)


# ==========================================================
# 1. Load
# تحميل البيانات
# ==========================================================

def load_data() -> pd.DataFrame:
    """
    قراءة البيانات الخام من CSV.

    نستخدم usecols لتحديد الأعمدة التي نحتاجها فقط.
    """

    return pd.read_csv(
        INPUT_FILE,
        usecols=[
            "student_id",
            "name",
            "gender",
            "city",
            "age",
            "gpa",
            "attendance"
        ]
    )


# ==========================================================
# 2. Clean
# تنظيف البيانات
# ==========================================================

def clean_data(
    df: pd.DataFrame
) -> pd.DataFrame:

    # نأخذ نسخة حتى لا نعدّل الـ DataFrame الأصلي مباشرة
    df = df.copy()

    # ------------------------------------------------------
    # حذف الطلاب المكررين اعتمادًا على student_id
    # ------------------------------------------------------

    df = df.drop_duplicates(
        subset=["student_id"]
    )

    # ------------------------------------------------------
    # تحويل الأعمدة الرقمية
    # ------------------------------------------------------
    # errors="coerce" يعني أن أي قيمة لا يمكن تحويلها
    # إلى رقم ستتحول إلى NaN

    df["age"] = pd.to_numeric(
        df["age"],
        errors="coerce"
    )

    df["gpa"] = pd.to_numeric(
        df["gpa"],
        errors="coerce"
    )

    df["attendance"] = pd.to_numeric(
        df["attendance"],
        errors="coerce"
    )

    # ------------------------------------------------------
    # التحقق من النطاقات المنطقية للبيانات
    # ------------------------------------------------------

    # العمر المقبول من 16 إلى 80
    # أي قيمة خارج هذا النطاق تتحول إلى NaN
    df["age"] = df["age"].where(
        df["age"].between(16, 80)
    )

    # GPA يجب أن يكون بين 0 و 4
    df["gpa"] = df["gpa"].where(
        df["gpa"].between(0, 4)
    )

    # الحضور يجب أن يكون بين 0 و 100
    df["attendance"] = (
        df["attendance"].where(
            df["attendance"].between(
                0,
                100
            )
        )
    )

    # ------------------------------------------------------
    # معالجة القيم المفقودة
    # ------------------------------------------------------
    # نستخدم Median كما تفعل المحاضرة

    df["age"] = df["age"].fillna(
        df["age"].median()
    )

    df["gpa"] = df["gpa"].fillna(
        df["gpa"].median()
    )

    df["attendance"] = (
        df["attendance"].fillna(
            df["attendance"].median()
        )
    )

    return df


# ==========================================================
# 3. Transform
# إنشاء Features جديدة
# ==========================================================

def transform(
    df: pd.DataFrame
) -> pd.DataFrame:

    # نأخذ نسخة مستقلة قبل إجراء التحويلات
    df = df.copy()

    # ------------------------------------------------------
    # تحويل الحضور من نسبة مئوية إلى قيمة بين 0 و 1
    # مثال:
    # 92 --> 0.92
    # ------------------------------------------------------

    df["attendance_rate"] = (
        df["attendance"] / 100
    )

    # ------------------------------------------------------
    # تحويل GPA إلى Performance Score من 100
    #
    # مثال:
    # GPA = 4.0 --> 100
    # GPA = 3.0 --> 75
    # ------------------------------------------------------

    df["performance_score"] = (
        df["gpa"] / 4 * 100
    )

    # ------------------------------------------------------
    # إنشاء تصنيف أكاديمي
    #
    # الطالب يعتبر High Performer إذا:
    # GPA >= 3.5
    # والحضور >= 90
    # ------------------------------------------------------

    df["academic_status"] = np.where(
        (
            (df["gpa"] >= 3.5)
            &
            (df["attendance"] >= 90)
        ),
        "High Performer",
        "Regular"
    )

    return df


# ==========================================================
# 4. Validate
# التحقق من صحة البيانات النهائية
# ==========================================================

def validate(
    df: pd.DataFrame
) -> None:

    # ------------------------------------------------------
    # لا نقبل DataFrame فارغ
    # ------------------------------------------------------

    if df.empty:
        raise ValueError(
            "Output DataFrame is empty."
        )

    # ------------------------------------------------------
    # student_id يجب أن يكون فريدًا
    # ------------------------------------------------------

    if not df["student_id"].is_unique:
        raise ValueError(
            "student_id must be unique."
        )

    # ------------------------------------------------------
    # جميع قيم GPA يجب أن تكون بين 0 و 4
    # ------------------------------------------------------

    if not df["gpa"].between(
        0,
        4
    ).all():
        raise ValueError(
            "Invalid GPA values."
        )

    # ------------------------------------------------------
    # جميع قيم الحضور يجب أن تكون بين 0 و 100
    # ------------------------------------------------------

    if not df["attendance"].between(
        0,
        100
    ).all():
        raise ValueError(
            "Invalid attendance values."
        )


# ==========================================================
# 5. Save
# حفظ البيانات النهائية
# ==========================================================

def save(
    df: pd.DataFrame
) -> None:

    # حفظ الناتج النهائي بدون عمود Index
    df.to_csv(
        OUTPUT_FILE,
        index=False
    )


# ==========================================================
# 6. Main Pipeline
# تشغيل مراحل الـ Pipeline بالترتيب
# ==========================================================

def main():

    print("1. Loading data...")

    df = load_data()

    print(
        "Rows loaded:",
        len(df)
    )

    # تنظيف البيانات
    print("2. Cleaning data...")

    df = clean_data(df)

    # إنشاء Features جديدة
    print("3. Transforming data...")

    df = transform(df)

    # التحقق من صحة النتيجة
    print("4. Validating data...")

    validate(df)

    # حفظ الناتج النهائي
    print("5. Saving data...")

    save(df)

    print("\nPipeline completed successfully.")

    print("\nFinal DataFrame:")
    print(df)


# ==========================================================
# تشغيل البرنامج
# ==========================================================

if __name__ == "__main__":
    main()